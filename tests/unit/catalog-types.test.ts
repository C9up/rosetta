/**
 * Codegen for typed translation keys. The generated text is the contract, so
 * the assertions pin the emitted types; `tests/types/typed-keys.fixture.ts`
 * (run by `pnpm test:types`) proves the result actually constrains `t()`.
 */
import ts from "typescript";
import { describe, expect, it } from "vitest";
import { generateCatalogTypes } from "../../src/CatalogTypes.js";

describe("generateCatalogTypes", () => {
	it("maps each ICU use of a variable to the type it accepts", () => {
		const out = generateCatalogTypes(
			{
				en: {
					greeting: "Hello {name}",
					items: "{count, plural, one {# item} other {# items}}",
					rank: "{place, selectordinal, one {#st} other {#th}}",
					total: "{amount, number, ::currency/USD}",
					when: "{at, date, short}",
					clock: "{at, time, short}",
					gender: "{g, select, male {his} female {her} other {their}}",
					plain: "Nothing to interpolate",
				},
			},
			{ referenceLocale: "en" },
		);

		expect(out).toContain("'greeting': { 'name': string | number }");
		expect(out).toContain("'items': { 'count': number }");
		expect(out).toContain("'rank': { 'place': number }");
		expect(out).toContain("'total': { 'amount': number }");
		expect(out).toContain("'when': { 'at': DateTimeValue }");
		expect(out).toContain("'clock': { 'at': DateTimeValue }");
		expect(out).toContain("'plain': Record<string, never>");
		// A select keeps its branches for autocomplete but still accepts other
		// strings, because an undeclared branch legally falls through to `other`.
		expect(out).toContain(
			"'gender': { 'g': 'male' | 'female' | (string & {}) }",
		);
	});

	it("emits a compilable augmentation of the rosetta module", () => {
		const out = generateCatalogTypes({ en: { a: "A" } });
		expect(out).toContain("declare module '@c9up/rosetta' {");
		expect(out).toContain("interface TranslationKeys {");
		expect(out).toContain("import type { DateTimeValue } from '@c9up/rosetta'");
		expect(out).toContain("// Generated by @c9up/rosetta — do not edit.");
	});

	it("targets another module when rosetta is re-exported", () => {
		const out = generateCatalogTypes(
			{ en: { a: "A" } },
			{ moduleName: "#i18n" },
		);
		expect(out).toContain("declare module '#i18n' {");
	});

	it("keeps a multi-variable message's fields together", () => {
		const out = generateCatalogTypes({
			en: { mix: "{name} has {n, plural, one {# thing} other {# things}}" },
		});
		expect(out).toContain("'mix': { 'n': number; 'name': string | number }");
	});

	it("skips an unparsable message rather than failing the build", () => {
		const out = generateCatalogTypes({
			en: { good: "Fine", broken: "{count, plural, one {#}" },
		});
		expect(out).toContain("'good': Record<string, never>");
		expect(out).not.toContain("'broken':");
		expect(out).toContain("Skipped 1 key(s)");
		expect(out).toContain("//   'broken'");
	});

	it("escapes quotes in keys and variable names", () => {
		const out = generateCatalogTypes({ en: { "it's": "Hi {name}" } });
		expect(out).toContain("'it\\'s'");
	});

	it("treats keys and variable names as data, never as source", () => {
		const hostile = [
			"line\nconst y = 1",
			"cr\rexport const z = 2",
			"ls\u2028export const w = 3",
			"ps\u2029export const v = 4",
			"quote' + process.exit(1) + '",
			"back\\slash",
			"nul\u0000tab\t",
			"lone\ud800surrogate",
		];
		const catalog: Record<string, string> = {};
		for (const key of hostile) catalog[key] = "Hi {name}";
		// The same strings as variable names, one message each, and as keys of
		// messages that do not parse (those are listed in a trailing comment).
		hostile.forEach((name, i) => {
			catalog[`p${i}`] = `{${name}}`;
		});
		for (const key of hostile) catalog[`${key} broken`] = "{n, plural, one {#}";
		const out = generateCatalogTypes({ en: catalog });

		const transpiled = ts.transpileModule(out, {
			reportDiagnostics: true,
			compilerOptions: { target: ts.ScriptTarget.ES2022 },
		});
		expect(transpiled.diagnostics ?? []).toEqual([]);

		const source = ts.createSourceFile(
			"i18n.d.ts",
			out,
			ts.ScriptTarget.ES2022,
		);
		const kinds = source.statements.map(
			(statement) => ts.SyntaxKind[statement.kind],
		);
		expect(kinds).toEqual(["ImportDeclaration", "ModuleDeclaration"]);
		// Every broken key is listed (a name ICU itself rejects adds its `p`).
		const listed = /Skipped (\d+) key\(s\)/.exec(out)?.[1];
		expect(Number(listed)).toBeGreaterThanOrEqual(hostile.length);
		expect(out).toContain(
			"'p0': { 'line\\u000aconst y = 1': string | number }",
		);
		expect(out).toContain(
			"'p2': { 'ls\\u2028export const w = 3': string | number }",
		);
		// Every line of the trailing listing is still a comment.
		const tail = out.slice(out.indexOf("// Skipped"));
		for (const line of tail.split(/\r\n|\r|\n|\u2028|\u2029/)) {
			expect(line === "" || line.startsWith("//")).toBe(true);
		}
	});

	it("keeps a printable non-ASCII key readable", () => {
		const out = generateCatalogTypes({ en: { "café.menu": "Menu" } });
		expect(out).toContain("'café.menu': Record<string, never>");
	});

	it("handles no catalogs and an unknown reference locale", () => {
		expect(generateCatalogTypes({})).toContain("interface TranslationKeys {");
		expect(
			generateCatalogTypes({ en: { a: "A" } }, { referenceLocale: "de" }),
		).not.toContain("'a':");
	});

	it("sorts keys, so regenerating produces no diff churn", () => {
		const out = generateCatalogTypes({ en: { zebra: "Z", apple: "A" } });
		expect(out.indexOf("'apple'")).toBeLessThan(out.indexOf("'zebra'"));
	});
});
